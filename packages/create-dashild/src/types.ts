export type Locale = "en" | "es";

export type PackageManager = "pnpm" | "npm" | "yarn" | "bun";

export type DatabaseProvider = "postgresql" | "mysql" | "sqlite";

export type AuthProvider = "better-auth" | "none";

export interface CreateOptions {
  /** Project name, used for package.json and the default directory. */
  name: string;
  /** Absolute target directory. */
  dir: string;
  /** `basic`, `demo`, `local:<path>`, `github:<owner>/<repo>` or a path. */
  template: string;
  auth: AuthProvider;
  database: DatabaseProvider;
  databaseUrl: string;
  directUrl?: string;
  packageManager: PackageManager;
  install: boolean;
  git: boolean;
  migrate: boolean;
  seed: boolean;
  panelPath: string;
  locale: Locale;
  yes: boolean;
  dryRun: boolean;
}

export interface CreateResult {
  projectDir: string;
  template: string;
  warnings: string[];
  /** Commands the user still has to run. */
  pending: string[];
  hasSeed: boolean;
  seeded: boolean;
}

export type CreateStep =
  | "scaffold"
  | "files"
  | "template"
  | "install"
  | "native"
  | "migrate"
  | "seed"
  | "git";

export interface TemplateManifest {
  name: string;
  version: string;
  description?: string;
  author?: string;
  license?: string;
  /** Semver range of Dashild this template supports. */
  dashild: string;
  prisma?: { provider?: DatabaseProvider[] };
  requires?: { auth?: AuthProvider[] };
  /** Extra Prisma fields added to a model generated by Dashild (for example User). */
  extend?: Record<string, string[]>;
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
  env?: string[];
}

export interface LoadedTemplate {
  manifest: TemplateManifest;
  /** Template files, keyed by their project-relative POSIX path. */
  files: Map<string, string>;
  source: string;
}
