import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

export const DASHILD_PACKAGES = [
  "@dashild/core",
  "@dashild/prisma",
  "@dashild/admin",
  "@dashild/cli",
] as const;

export type DashildPackage = (typeof DASHILD_PACKAGES)[number];
export type UpgradeTag = "latest" | "alpha";
export type PackageManager = "pnpm" | "npm" | "yarn" | "bun";

export interface GlueFile {
  path: string;
  version: string | null;
}

export interface UpgradeResult {
  current: Record<DashildPackage, string>;
  target: string;
  outdated: boolean;
  updated: boolean;
  installed: boolean;
  generated: boolean;
  packageManager: PackageManager;
  glue: GlueFile[];
  notes: string[];
}

export interface UpgradeOptions {
  cwd: string;
  tag?: UpgradeTag;
  version?: string;
  check?: boolean;
  dryRun?: boolean;
  install?: boolean;
  generate?: boolean;
  /** Test hook: resolve a dist-tag without the network. */
  resolveTarget?: (name: string, tag: string) => Promise<string | null>;
  /** Test hook: run install/generate commands. */
  run?: (command: string, args: string[], cwd: string) => void;
}

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(path, "utf8")) as T;
}

function detectPackageManager(cwd: string, packageJson: {
  packageManager?: string;
}): PackageManager {
  const pinned = packageJson.packageManager?.split("@")[0];
  if (pinned === "pnpm" || pinned === "npm" || pinned === "yarn" || pinned === "bun") {
    return pinned;
  }
  if (existsSync(resolve(cwd, "pnpm-lock.yaml"))) return "pnpm";
  if (existsSync(resolve(cwd, "yarn.lock"))) return "yarn";
  if (
    existsSync(resolve(cwd, "bun.lock")) ||
    existsSync(resolve(cwd, "bun.lockb"))
  ) {
    return "bun";
  }
  if (existsSync(resolve(cwd, "package-lock.json"))) return "npm";
  return "npm";
}

async function fetchDistTag(name: string, tag: UpgradeTag): Promise<string | null> {
  const url = `https://registry.npmjs.org/${name.replace("/", "%2f")}`;
  const response = await fetch(url, {
    headers: { accept: "application/json" },
    signal: AbortSignal.timeout(20_000),
  });
  if (!response.ok) return null;
  const data = (await response.json()) as {
    "dist-tags"?: Record<string, string>;
  };
  return data["dist-tags"]?.[tag] ?? null;
}

function gluePaths(cwd: string, panelPath: string): string[] {
  return [
    "src/dashild/panel.ts",
    "src/dashild/policies.ts",
    "src/dashild/actions/index.ts",
    "src/dashild/icons.tsx",
    "src/dashild/runtime.ts",
    "src/dashild/server.ts",
    "src/dashild/registry.tsx",
    "src/dashild/organization-actions.ts",
    "src/lib/session.ts",
    "src/lib/auth-actions.ts",
    `src/app${panelPath}/[[...dashild]]/page.tsx`,
    `app${panelPath}/[[...dashild]]/page.tsx`,
  ].map((path) => resolve(cwd, path));
}

function scanGlue(cwd: string, panelPath: string): GlueFile[] {
  return gluePaths(cwd, panelPath)
    .filter((path) => existsSync(path))
    .map((path) => {
      const head = readFileSync(path, "utf8").split("\n", 12).join("\n");
      const match = head.match(/\/\/ dashild:generated (\S+)/);
      return {
        path: path.slice(cwd.length + 1).replace(/\\/g, "/"),
        version: match?.[1] ?? null,
      };
    });
}

function defaultRun(command: string, args: string[], cwd: string): void {
  const result = spawnSync(command, args, { cwd, stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} exited with ${result.status}`);
  }
}

function runBinary(
  cwd: string,
  binary: string,
  args: string[],
  run: NonNullable<UpgradeOptions["run"]>,
): void {
  const local = resolve(cwd, "node_modules/.bin", binary);
  if (existsSync(local)) {
    run(local, args, cwd);
    return;
  }
  run(binary, args, cwd);
}

/**
 * Updates the Dashild stack pinned in the app, regenerates the Prisma metadata
 * and reports glue generated by an older CLI.
 *
 * It never rewrites the app's glue: those files are write-once and belong to
 * the developer. The marker (`// dashild:generated <version>`) tells the
 * command which files came from an older generator.
 */
export async function upgrade(options: UpgradeOptions): Promise<UpgradeResult> {
  const cwd = resolve(options.cwd);
  const packageJsonPath = resolve(cwd, "package.json");
  if (!existsSync(packageJsonPath)) {
    throw new Error(`No package.json in ${cwd}`);
  }

  const packageJson = readJson<{
    packageManager?: string;
    dependencies?: Record<string, string>;
    devDependencies?: Record<string, string>;
  }>(packageJsonPath);

  const current = {} as Record<DashildPackage, string>;
  for (const name of DASHILD_PACKAGES) {
    const version =
      packageJson.dependencies?.[name] ?? packageJson.devDependencies?.[name];
    if (!version) {
      throw new Error(
        `${name} is not a dependency; this does not look like a Dashild app.`,
      );
    }
    current[name] = version;
  }

  const tag = options.tag ?? "latest";
  const resolveTarget = options.resolveTarget ?? fetchDistTag;
  let target = options.version;

  if (!target) {
    const resolved = await Promise.all(
      DASHILD_PACKAGES.map((name) => resolveTarget(name, tag)),
    );
    if (resolved.some((version) => !version)) {
      throw new Error(`Could not resolve the ${tag} version from npm.`);
    }
    const unique = [...new Set(resolved)];
    if (unique.length > 1 || !unique[0]) {
      throw new Error(
        `The Dashild packages are not in lockstep on ${tag}: ${resolved.join(", ")}`,
      );
    }
    target = unique[0];
  }

  const dashildJsonPath = resolve(cwd, "dashild.json");
  const dashildJson = existsSync(dashildJsonPath)
    ? readJson<{ panelPath?: string; stackVersion?: string }>(dashildJsonPath)
    : null;
  const panelPath = dashildJson?.panelPath ?? "/admin";

  const packageManager = detectPackageManager(cwd, packageJson);
  const glue = scanGlue(cwd, panelPath);
  const outdated = DASHILD_PACKAGES.some(
    (name) => current[name] !== target,
  );
  const notes: string[] = [];

  if (!dashildJson) {
    notes.push("No dashild.json; the stack version will not be recorded.");
  }
  if (glue.some((file) => file.version === null)) {
    notes.push(
      "Some glue files predate version markers; review them manually (see the Upgrading guide).",
    );
  }

  const result: UpgradeResult = {
    current,
    target,
    outdated,
    updated: false,
    installed: false,
    generated: false,
    packageManager,
    glue,
    notes,
  };

  if (options.check || options.dryRun) return result;

  if (outdated) {
    const next = {
      ...packageJson,
      dependencies: { ...packageJson.dependencies },
      devDependencies: { ...packageJson.devDependencies },
    };
    for (const name of DASHILD_PACKAGES) {
      if (next.dependencies?.[name]) next.dependencies[name] = target;
      else if (next.devDependencies?.[name]) next.devDependencies[name] = target;
    }
    writeFileSync(packageJsonPath, `${JSON.stringify(next, null, 2)}\n`, "utf8");
    result.updated = true;
  }

  if (dashildJson) {
    writeFileSync(
      dashildJsonPath,
      `${JSON.stringify({ ...dashildJson, stackVersion: target }, null, 2)}\n`,
      "utf8",
    );
  }

  const run = options.run ?? defaultRun;

  if (options.install !== false) {
    run(packageManager, ["install"], cwd);
    result.installed = true;
  }

  if (options.generate !== false) {
    runBinary(cwd, "prisma", ["generate"], run);
    result.generated = true;
  }

  return result;
}
